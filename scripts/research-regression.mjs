import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFile } from "node:fs/promises";
const require = createRequire(import.meta.url);
const browser = require(new URL("../api/_research-browser.js", import.meta.url).pathname);
const orchestrator = require(new URL("../api/_research-orchestrator.js", import.meta.url).pathname);
assert.equal(browser.isPrivateAddress("127.0.0.1"), true);
assert.equal(browser.isPrivateAddress("169.254.169.254"), true);
assert.equal(browser.isPrivateAddress("10.0.0.1"), true);
assert.equal(browser.isPrivateAddress("192.168.1.1"), true);
assert.equal(browser.isPrivateAddress("8.8.8.8"), false);
assert.equal(browser.isPrivateAddress("2001:4860:4860::8888"), false);
await assert.rejects(() => browser.assertSafeUrl("http://localhost/admin"));
await assert.rejects(() => browser.assertSafeUrl("http://169.254.169.254/latest/meta-data"));
await assert.rejects(() => browser.assertSafeUrl("file:///etc/passwd"));
assert.equal(orchestrator.researchToolDefinition.function.name, "research_web");
assert.equal(orchestrator.DEFAULT_BUDGETS.normal.actions, 16);
assert.equal(orchestrator.DEFAULT_BUDGETS.deep.pages, 18);
const api = await readFile(new URL("../api/research.js", import.meta.url), "utf8");
assert.match(api, /authenticateUser/);
assert.match(api, /runResearch/);
assert.match(api, /evidence/);
const browserSource = await readFile(new URL("../api/_research-browser.js", import.meta.url), "utf8");
assert.match(browserSource, /playwright-core/);
assert.match(browserSource, /route\.abort/);
assert.match(browserSource, /page\.goto/);
console.log("research-regression: OK — navegador real opcional, SSRF, limites, evidências e API verificados.");
